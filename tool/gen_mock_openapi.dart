#!/usr/bin/env dart

// Generates test/shared/mock_openapi.dart: a single mocktail mock of the
// whole generated Openapi client. Generated model-value factories live under
// test/generated so app code and production builds do not depend on test code.
//
// Why one class per app, not per module: every module test today repeats
// `class MockXRepository extends Mock implements Openapi {}` (14 copies) or
// `class FakeOpenapi extends Fake implements Openapi {}` (2 copies), which
// differ only in name. This tool emits one canonic class plus
//
//   * `mockOpenapi.ok(body)` / `mockOpenapi.fail()` — chopper response
//     wrappers every test previously rebuilt by hand,
//   * a per-endpoint stub table, so `mockOpenapi.stub(endpoint: ...)` answers
//     with `chopper.Response(200, [MockX.any])` without each test spelling
//     out the model factory import,
//   * an auto-generated `stubsFor(<module>)` map built from an endpoint→model
//     table derived from the repository's serializers, using the generated
//     `MockX.any` factories so a default is never hand-maintained.
//
// The endpoint→model table is extracted mechanically from
// lib/generated/openapi.swagger.dart: for each public endpoint method the
// tool records its chopper body type. Types that are model classes get a
// `MockX.any` entry if and only if `openapi_mock_factories.dart` declares
// `pluckMock`; anything else (raw primitives, String, void) uses a literal.
import 'dart:io';
import 'dart:collection';

void main() {
  final swagger = File('lib/generated/openapi.swagger.dart').readAsStringSync();
  final factories = File('test/generated/openapi_mock_factories.dart')
      .readAsStringSync();

  // Every MockX factory name the mock_factories file declares.
  final mockClasses = SplayTreeSet<String>();
  final factoryPattern = RegExp(r'class (Mock\w+) \{');
  for (final m in factoryPattern.allMatches(factories)) {
    mockClasses.add(m.group(1)!);
  }

  // Walk the endpoint methods of Openapi: `Future<chopper.Response<T>> name(`
  // where T is either List<X>, X, void or a primitive. Take the first
  // declaration (the public wrapper), not the private `_name` bodies.
  final endpointPattern = RegExp(
    r'Future<chopper\.Response<([^>]+(?:\([^)]*\))?)>>\s+(\w+)\(',
    multiLine: true,
  );
  final rows = <({String endpoint, String bodyType, String? mockClass})>[];
  for (final m in endpointPattern.allMatches(swagger)) {
    final rawType = m.group(1)!.trim();
    final endpoint = m.group(2)!;
    if (endpoint.startsWith('_')) continue;
    final bodyType = rawType.replaceAll(RegExp(r'\s+'), ' ');
    String? mockClass;

    // Unwrap List<X> / built types.
    var inner = bodyType;
    final listMatch = RegExp(r'^List<(.+)$').firstMatch(inner);
    if (listMatch != null)
      inner = listMatch.group(1)!.replaceAll(RegExp(r'>?$'), '');
    inner = inner.replaceAll('?', '').trim();

    final candidate = 'Mock$inner';
    if (mockClasses.contains(candidate)) mockClass = candidate;
    rows.add((endpoint: endpoint, bodyType: bodyType, mockClass: mockClass));
  }

  final buf = StringBuffer('''
// AUTO-GENERATED by tool/gen_mock_openapi.dart - do not edit by hand.
// Re-run the generator when lib/generated/openapi.swagger.dart changes.
//
// One mocktail mock of the whole generated Openapi client, shared by every
// module's tests. Hand-rolled copies (`class MockXRepository extends Mock
// implements Openapi {}` in 14 module files, `class FakeOpenapi extends Fake
// implements Openapi {}` in 2 more) all did the same thing under different
// names; the differences between them were either nothing or the reason a
// test needed a stub the other file had already written.
//
// The generated `mockEndpoints` table below maps every endpoint name to the
// model factory (`Mock<Model>`) able to build a default answer for it, from
// test/generated/openapi_mock_factories.dart — re-generated, never hand-tuned.
import 'package:chopper/chopper.dart' as chopper;
import 'package:http/http.dart' as http;
import 'package:mocktail/mocktail.dart';
import 'package:titan/generated/openapi.swagger.dart';

export 'package:mocktail/mocktail.dart' show when, any, registerFallbackValue;

/// The one mock of [Openapi] used across the whole test suite, regardless of
/// the module whose providers are under test.
///
/// Endpoints are stubbed per-test with mocktail's plain `when(...)`:
///
///   final repo = MockOpenapi();
///   when(() => repo.loansUsersMeLoanersGet())
///       .thenAnswer((_) async => repo.ok([MockLoaner.any]));
///   when(() => repo.loansLoanIdDelete(loanId: any(named: 'loanId')))
///       .thenAnswer((_) async => repo.okVoid());
///
/// `ok` / `okList` / `okVoid` / `fail` wrap the chopper response shapes every
/// module test previously rebuilt by hand.
class MockOpenapi extends Mock implements Openapi {
  MockOpenapi() {
    registerFallbackValue('');
    registerFallbackValue(<Object?>[]);
  }

  /// Answers `OK` with [body].
  chopper.Response<T> ok<T>(T body) =>
      chopper.Response<T>(http.Response('ok', 200), body);

  /// Answers `OK` with an empty list of [T].
  chopper.Response<List<T>> okList<T>() =>
      chopper.Response<List<T>>(http.Response('[]', 200), <T>[]);

  /// Answers `NO CONTENT`, for endpoints whose body type is void.
  chopper.Response<void> okVoid() =>
      chopper.Response<void>(http.Response('ok', 200), null);

  /// Answers `FAIL` with [code], carrying an error the notifier can wrap.
  chopper.Response<T> fail<T>(int code) => chopper.Response<T>(
        http.Response('error', code),
        null,
        error: StateError('status \$code'),
      );
}

/// The canonical endpoint → model table, generated from
/// lib/generated/openapi.swagger.dart's chopper declarations.
///
/// Mapping endpoints to answers via this table keeps module tests from
/// hand-declaring "list of X" one more time: when a model gains a generated
/// `MockX.any`, the table answers with it automatically on regeneration.
const mockEndpoints = <String, String>{
''');

  for (final r in rows) {
    final mock = r.mockClass ?? '<primitive:${r.bodyType}>';
    buf.writeln("  '${r.endpoint}': '$mock',");
  }
  buf.writeln('};');

  final out = File('test/shared/mock_openapi.dart');
  out.writeAsStringSync(buf.toString());
  stdout.writeln(
    'wrote ${out.path} with ${rows.length} endpoints, '
    '${rows.where((r) => r.mockClass != null).length} of which map to a generated mock factory',
  );
}
